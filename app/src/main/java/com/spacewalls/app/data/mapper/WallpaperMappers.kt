package com.spacewalls.app.data.mapper

import com.spacewalls.app.data.license.LicensePolicy
import com.spacewalls.app.data.model.ImageSource
import com.spacewalls.app.data.model.RightsStatus
import com.spacewalls.app.data.model.Wallpaper
import com.spacewalls.app.data.remote.nasa.NasaItem
import com.spacewalls.app.data.remote.nasa.NasaLink
import com.spacewalls.app.data.remote.wikimedia.WikimediaPage
import com.spacewalls.app.util.HtmlText

/**
 * DTO -> domain. Every function returns null when the source did not give us
 * enough to credit and licence the image properly; such items are silently
 * dropped and never reach the UI.
 */
object WallpaperMappers {

    fun fromWikimedia(page: WikimediaPage): Wallpaper? {
        val pageId = page.pageId ?: return null
        val info = page.imageInfo?.firstOrNull() ?: return null
        val meta = info.extMetadata.orEmpty()
        fun value(key: String): String = HtmlText.strip(meta[key]?.value)

        val decision = LicensePolicy.evaluateWikimedia(
            licenseShortName = value("LicenseShortName"),
            licenseUrl = value("LicenseUrl"),
            usageTerms = value("UsageTerms"),
            restrictions = value("Restrictions"),
            artist = value("Artist"),
            descriptionPageUrl = info.descriptionUrl,
            mime = info.mime,
            width = info.width ?: 0,
            height = info.height ?: 0
        ) ?: return null

        val originalUrl = info.url ?: return null
        val previewUrl = info.thumbUrl ?: originalUrl

        val rawTitle = (page.title ?: "Wikimedia image")
            .removePrefix("File:")
            .substringBeforeLast('.')
            .replace('_', ' ')
            .trim()

        val creator = value("Artist").ifBlank { value("Credit").ifBlank { "Unknown author" } }

        return Wallpaper(
            id = "wikimedia:$pageId",
            source = ImageSource.WIKIMEDIA,
            remoteId = pageId.toString(),
            title = rawTitle.ifBlank { "Wikimedia image" },
            description = HtmlText.summarize(value("ImageDescription"), 420),
            creator = creator,
            credit = value("Credit"),
            licenseName = decision.licenseName,
            licenseUrl = decision.licenseUrl,
            usageTerms = decision.usageTerms,
            sourceName = ImageSource.WIKIMEDIA.displayName,
            sourcePageUrl = info.descriptionUrl.orEmpty(),
            originalUrl = originalUrl,
            previewUrl = previewUrl,
            thumbUrl = previewUrl,
            width = info.width ?: 0,
            height = info.height ?: 0,
            mimeType = info.mime.orEmpty(),
            dateCreated = value("DateTimeOriginal").ifBlank { value("DateTime") }.ifBlank { null },
            modifications = "Original file unmodified. The preview shown is a thumbnail " +
                "generated by Wikimedia Commons; the full-resolution file is downloaded untouched.",
            rightsStatus = decision.rightsStatus,
            rightsNote = decision.note
        )
    }

    fun fromNasa(item: NasaItem): Wallpaper? {
        val data = item.data?.firstOrNull() ?: return null
        if (data.mediaType != null && data.mediaType != "image") return null
        val nasaId = data.nasaId ?: return null

        val links = item.links.orEmpty()
        val canonical = links.firstOrNull {
            it.rel == "canonical" && !it.href.isNullOrBlank()
        }
        val fallback = links
            .filter { it.rel == "alternate" && !it.href.isNullOrBlank() }
            .maxByOrNull { (it.width ?: 0) * (it.height ?: 0) }
        val chosen: NasaLink = canonical ?: fallback ?: return null

        val originalUrl = chosen.href?.replace("http://", "https://") ?: return null
        val preview = links
            .filter { it.rel == "alternate" && it.href != null }
            .maxByOrNull { (it.width ?: 0) * (it.height ?: 0) }
            ?.href?.replace("http://", "https://")
            ?: originalUrl

        val width = chosen.width ?: 0
        val height = chosen.height ?: 0

        val decision = LicensePolicy.evaluateNasa(
            center = data.center,
            secondaryCreator = data.secondaryCreator,
            title = data.title,
            description = data.description,
            originalUrl = originalUrl,
            width = width,
            height = height
        ) ?: return null

        val creatorLine = listOfNotNull(
            data.secondaryCreator?.trim()?.takeIf { it.isNotBlank() },
            data.center?.trim()?.takeIf { it.isNotBlank() }?.let { "NASA/$it" }
        ).joinToString(" / ").ifBlank { "NASA" }

        val title = data.title?.trim().orEmpty().ifBlank { nasaId }

        return Wallpaper(
            id = "nasa:$nasaId",
            source = ImageSource.NASA,
            remoteId = nasaId,
            title = title,
            description = HtmlText.summarize(data.description ?: data.descriptionAlt, 420),
            creator = creatorLine,
            credit = listOfNotNull(data.secondaryCreator, data.center?.let { "NASA/$it" })
                .joinToString(" — ").ifBlank { "NASA" },
            licenseName = decision.licenseName,
            licenseUrl = decision.licenseUrl,
            usageTerms = decision.usageTerms,
            sourceName = ImageSource.NASA.displayName,
            sourcePageUrl = "https://images.nasa.gov/details/$nasaId",
            originalUrl = originalUrl,
            previewUrl = preview,
            thumbUrl = preview,
            width = width,
            height = height,
            mimeType = if (originalUrl.endsWith(".png", true)) "image/png" else "image/jpeg",
            dateCreated = data.dateCreated,
            modifications = "Original NASA asset unmodified.",
            rightsStatus = decision.rightsStatus,
            rightsNote = decision.note
        )
    }

    /** Some NASA collections report a partner credit only in keywords. */
    fun hasPartnerCredit(keywords: List<String>?): Boolean {
        val joined = keywords?.joinToString(" ")?.lowercase() ?: return false
        return listOf("esa", "eso", "jaxa").any { joined.contains(it) }
    }
}
